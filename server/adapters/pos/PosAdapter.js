/**
 * POS adapter contract.
 *
 * ==========================================================================
 * THE CORE ARCHITECTURAL RULE OF THIS PROJECT
 * ==========================================================================
 * The coffee shop's own POS is the source of truth for the menu, item IDs,
 * modifiers, availability, prices, taxes, order records and order status. The
 * kiosk is a new ORDERING CHANNEL, not a replacement POS.
 *
 * Every piece of kiosk code reaches the POS only through this interface.
 * Nothing outside `server/adapters/pos/` may open a POS database, know a POS
 * table name, or compute an authoritative price. Integrating a real client POS
 * means writing one new class that implements these methods — no route,
 * service or React component changes.
 *
 * DemoPosAdapter implements this today and stands in for the client's POS
 * during the proof of concept. Future adapters (REST, local API, file drop,
 * middleware) implement the same methods.
 *
 * All monetary values are INTEGER minor currency units and all product prices
 * are VAT-INCLUSIVE. See shared/money.js.
 */

/** Raised when the POS cannot be reached or answers unusably. Retryable. */
export class PosIntegrationError extends Error {
  constructor(message, { code = 'pos_unavailable', retryable = true, details, cause } = {}) {
    super(message);
    this.name = 'PosIntegrationError';
    this.code = code;
    this.retryable = retryable;
    this.details = details;
    if (cause) this.cause = cause;
  }
}

/** Raised when the POS understood the request and refused it. Not retryable. */
export class PosRejectedError extends Error {
  constructor(message, { code = 'pos_rejected', details, cause } = {}) {
    super(message);
    this.name = 'PosRejectedError';
    this.code = code;
    this.retryable = false;
    this.details = details;
    if (cause) this.cause = cause;
  }
}

