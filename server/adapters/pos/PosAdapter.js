/**
 * Abstract base. Subclasses must implement every method; the defaults throw so
 * a half-written adapter fails loudly instead of silently returning undefined.
 */
export class PosAdapter {
  /** Short identifier used in logs and the health endpoint. */
  get name() {
    return 'abstract';
  }

  /** @returns {Promise<CanonicalMenu>} Full catalog with modifiers. */
  async getMenu() {
    throw new Error(`${this.constructor.name} must implement getMenu()`);
  }

  /**
   * Cheap availability/price delta check for frequent polling.
   * @returns {Promise<{menuVersion:string, items:{posProductId:string, available:boolean, priceMinor:number}[]}>}
   */
  async getAvailability() {
    throw new Error(`${this.constructor.name} must implement getAvailability()`);
  }

  /**
   * Price a cart. The POS owns this calculation — the kiosk displays the
   * result and never computes a total it then charges.
   * @param {QuoteRequest} request
   * @returns {Promise<CanonicalQuote>}
   */
  async calculateQuote(request) {
    throw new Error(`${this.constructor.name} must implement calculateQuote()`);
  }

  /**
   * Validate a promo code or loyalty identifier.
   * @returns {Promise<{valid:boolean, reason?:string, kind?:string, descriptionEn?:string, descriptionAr?:string}>}
   */
  async validateCouponOrLoyalty(_input) {
    throw new Error(`${this.constructor.name} must implement validateCouponOrLoyalty()`);
  }

  /**
   * Create an order in the POS. MUST be idempotent on clientRequestId: calling
   * it twice with the same key returns the same order with duplicate=true and
   * never creates a second order or a second charge.
   * @param {SubmitOrderRequest} request
   * @returns {Promise<CanonicalOrder>}
   */
  async submitOrder(_request) {
    throw new Error(`${this.constructor.name} must implement submitOrder()`);
  }

  /** Attach a payment outcome to an existing POS order. Idempotent per reference. */
  async attachPayment(_input) {
    throw new Error(`${this.constructor.name} must implement attachPayment()`);
  }

  /**
   * Debit a gift card. Must be atomic with its ledger entry: a balance that
   * moves without a ledger row, or the reverse, is unreconcilable money.
   * @returns {Promise<{code:string, redeemedMinor:number, balanceMinor:number, currency:string}>}
   */
  async redeemGiftCard(_input) {
    throw new Error(`${this.constructor.name} must implement redeemGiftCard()`);
  }

  /** @returns {Promise<CanonicalOrder>} */
  async getOrderStatus(_posOrderId) {
    throw new Error(`${this.constructor.name} must implement getOrderStatus()`);
  }

  /** @returns {Promise<{healthy:boolean, latencyMs:number, detail?:string}>} */
  async health() {
    throw new Error(`${this.constructor.name} must implement health()`);
  }
}
