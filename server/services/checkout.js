import { PosIntegrationError, PosRejectedError } from '../adapters/pos/PosAdapter.js';
import { badRequest, conflict, menuChanged, notFound, posUnavailable, validationFailed, AppError } from '../lib/errors.js';

/**
 * Checkout: quoting, order submission, and the durable retry queue.
 *
 * Two properties this file exists to guarantee:
 *
 * 1. **The browser never sets a price.** A quote is computed by the POS, stored
 *    server-side, and handed to the client as an opaque ID. At checkout the
 *    cart is re-priced by the POS and compared; the POS is given the expected
 *    total and refuses on mismatch. Three independent checks, because a
 *    self-service terminal is a public machine.
 *
 * 2. **An order is never lost and never duplicated.** A durable row is written
 *    BEFORE the POS is called, keyed on a client-generated request ID with a
 *    UNIQUE constraint. A crash between write and confirm leaves a pending row
 *    the queue retries; a retried POST finds the original row and returns it.
 *    The POS deduplicates on the same key, so both sides hold the line.
 */

const CLIENT_REQUEST_ID_PATTERN = /^[\w-]{8,100}$/;

export class CheckoutService {
  constructor({ adapter, kioskStore, menuSync, storeId, logger }) {
    this.adapter = adapter;
    this.kioskStore = kioskStore;
    this.menuSync = menuSync;
    this.storeId = storeId;
    this.logger = logger;
    this.queueTimer = null;
  }

  // ------------------------------------------------------------------ quotes

  /**
   * Price a cart through the POS and persist the result.
   *
   * Product references may be POS IDs or kiosk-local keys; unmapped references
   * are rejected and logged as integration problems rather than passed through.
   */
  async createQuote({ kioskId, cart }) {
    const lines = Array.isArray(cart?.lines) ? cart.lines : null;
    if (!lines || lines.length === 0) throw badRequest('Your order is empty.');
    if (!['dine_in', 'takeaway'].includes(cart.fulfillment)) {
      throw validationFailed('Choose dine-in or takeaway.', { field: 'fulfillment' });
    }

    const store = this.kioskStore.getStore(this.storeId);
    if (cart.fulfillment === 'dine_in' && store && !store.dineInEnabled) {
      throw validationFailed('Dine-in is not available at this store.', { field: 'fulfillment' });
    }

    const resolvedLines = [];
    const unresolved = [];
    for (const [index, line] of lines.entries()) {
      const ref = String(line.posProductId ?? line.productId ?? '').trim();
      if (!ref) {
        throw validationFailed('An item is missing its product reference.', { lineIndex: index });
      }
      const posProductId = this.menuSync.resolveProductRef(ref);
      if (!posProductId) {
        unresolved.push({ lineIndex: index, reference: ref });
        continue;
      }
      resolvedLines.push({
        posProductId,
        quantity: Number(line.quantity),
        modifierIds: Array.isArray(line.modifierIds) ? line.modifierIds.map(String) : [],
        notes: typeof line.notes === 'string' ? line.notes : '',
      });
    }

    if (unresolved.length > 0) {
      // Deliberately a hard failure. Guessing a product here would mean
      // charging a customer for something the till does not recognise.
      throw new AppError('mapping_missing', 'Part of this order is not set up on the till. Please ask a member of staff.', {
        status: 409,
        details: { unresolved },
      });
    }

    const request = {
      storeId: this.storeId,
      fulfillment: cart.fulfillment,
      tableNumber: normaliseTableNumber(cart.tableNumber, store),
      promotionCode: cart.promotionCode ? String(cart.promotionCode).trim().toUpperCase() : null,
      lines: resolvedLines,
    };

    let quote;
    try {
      quote = await this.adapter.calculateQuote(request);
    } catch (error) {
      throw translatePosError(error);
    }

    const stored = this.kioskStore.createQuote({
      storeId: this.storeId,
      kioskId,
      request,
      quote,
      menuVersion: quote.menuVersion,
    });

    this.kioskStore.logEvent({
      storeId: this.storeId,
      kioskId,
      eventType: 'quote.created',
      payload: { quoteId: stored.id, totalMinor: quote.totalMinor, currency: quote.currency, lines: resolvedLines.length },
    });

    return { quoteId: stored.id, expiresAt: stored.expiresAt, quote };
  }

  // ------------------------------------------------------------------ submit

  /**
   * Submit an order. Idempotent on clientRequestId.
   *
   * @param {object} args
   * @param {string} args.clientRequestId  Stable key generated by the kiosk.
   * @param {string} args.quoteId
   * @param {object} [args.payment]  Payment outcome, when one has been taken.
   */
  async submitOrder({ clientRequestId, quoteId, kioskId, notes, payment = null }) {
    const key = String(clientRequestId ?? '').trim();
    if (!CLIENT_REQUEST_ID_PATTERN.test(key)) {
      throw validationFailed(
        'A valid clientRequestId is required so a retry cannot create a second order.',
        { field: 'clientRequestId' },
      );
    }

    // ---- 1. idempotency: has this exact submission been seen before? ------
    const existing = this.kioskStore.findSubmission(key);
    if (existing) {
      if (existing.status === 'submitted') {
        const order = await this.adapter.getOrderStatus(existing.posOrderId).catch(() => null);
        return {
          duplicate: true,
          status: 'confirmed',
          posOrderId: existing.posOrderId,
          posOrderNumber: existing.posOrderNumber,
          order,
        };
      }
      // Still in flight: nudge it rather than creating a parallel attempt.
      const retried = await this.#attemptSubmission(existing);
      return { duplicate: true, ...retried };
    }

    // ---- 2. the quote must be real, open, unexpired, and current ----------
    // If a payment has already been approved, every rejection below has to
    // leave a durable trace before it throws. Otherwise a customer whose card
    // was charged in the second before a price change would get an error
    // screen and we would hold no record of their money at all. So the
    // validation runs inside a guard that files an ops exception first.
    const paymentAccepted = payment?.status === 'approved';
    if (paymentAccepted) {
      try {
        return await this.#validateAndSubmit({ key, quoteId, kioskId, notes, payment });
      } catch (error) {
        this.#recordStrandedPayment({ key, kioskId, quoteId, payment, error });
        // Do not show a paying customer "please review your order" — their
        // money has already moved. Tell them plainly and give them the
        // reference a member of staff needs to resolve it.
        throw new AppError(
          'payment_taken_order_failed',
          'Your payment went through, but we could not send your order to the till. '
            + 'Please show a member of staff this reference so they can sort it out.',
          {
            status: 409,
            details: {
              reference: payment?.reference ?? null,
              clientRequestId: key,
              underlyingCode: error.code ?? 'unknown',
            },
          },
        );
      }
    }
    return this.#validateAndSubmit({ key, quoteId, kioskId, notes, payment });
  }

  /**
   * Durably record a payment that was accepted but could not become an order.
   *
   * This is the last line of defence: the customer's money has moved and no
   * POS order exists, so the only acceptable outcome is that a human is told.
   * Recorded on a best-effort basis — a failure here must not replace the
   * original error the customer is waiting on.
   */
  #recordStrandedPayment({ key, kioskId, quoteId, payment, error }) {
    try {
      if (!this.kioskStore.findSubmission(key)) {
        this.kioskStore.createSubmission({
          clientRequestId: key,
          storeId: this.storeId,
          kioskId,
          quoteId: null,
          payload: { strandedPayment: true, quoteId, payment, reason: error.code ?? 'unknown' },
          paymentAccepted: true,
          paymentReference: payment?.reference ?? null,
        });
        // Nothing can be retried automatically: the cart could not be priced,
        // so there is no order to create. Mark it terminal for the worker and
        // leave it visible as an exception.
        const created = this.kioskStore.findSubmission(key);
        this.kioskStore.markSubmissionFailed(created.id, { error: error.message, retryable: false });
      }
      this.kioskStore.recordIntegrationIssue(
        this.storeId,
        'paid_order_not_created',
        `Payment ${payment?.reference ?? '(no reference)'} was approved but no order could be created: ${error.message}`,
      );
      this.kioskStore.logEvent({
        storeId: this.storeId, kioskId, level: 'error',
        eventType: 'payment.stranded',
        message: 'Approved payment with no POS order.',
        payload: { clientRequestId: key, reason: error.code ?? 'unknown', reference: payment?.reference ?? null },
      });
      this.logger?.error?.('checkout.payment_stranded', {
        clientRequestId: key, reference: payment?.reference ?? null, reason: error.code ?? 'unknown',
      });
    } catch (recordingError) {
      this.logger?.error?.('checkout.stranded_record_failed', { message: recordingError.message });
    }
  }

  async #validateAndSubmit({ key, quoteId, kioskId, notes, payment }) {
    const stored = this.kioskStore.getQuote(quoteId);
    if (!stored) throw notFound('That order summary has expired. Please review your order.');
    if (stored.storeId !== this.storeId) throw notFound('That order summary belongs to another store.');
    if (stored.status === 'consumed') {
      throw conflict('That order summary has already been used.', { quoteId });
    }
    if (stored.status === 'invalidated') {
      throw menuChanged('The menu changed while you were ordering. Please review your order.', { quoteId });
    }
    if (stored.expired) {
      this.kioskStore.markQuote(quoteId, 'expired');
      throw conflict('That order summary has expired. Please review your order.', { quoteId });
    }

    const liveMenu = this.menuSync.getKioskMenu();
    if (liveMenu.available && liveMenu.menuVersion !== stored.menuVersion) {
      this.kioskStore.markQuote(quoteId, 'invalidated');
      throw menuChanged('Prices or availability changed while you were ordering. Please review your order.', {
        quoteId, quotedMenuVersion: stored.menuVersion, currentMenuVersion: liveMenu.menuVersion,
      });
    }

    // ---- 3. re-price against the POS before taking any money --------------
    let fresh;
    try {
      fresh = await this.adapter.calculateQuote(stored.request);
    } catch (error) {
      throw translatePosError(error);
    }
    if (fresh.totalMinor !== stored.totalMinor) {
      this.kioskStore.markQuote(quoteId, 'invalidated');
      this.kioskStore.logEvent({
        storeId: this.storeId, kioskId, level: 'warn', eventType: 'quote.total_changed',
        payload: { quoteId, was: stored.totalMinor, now: fresh.totalMinor },
      });
      throw menuChanged('The total changed while you were ordering. Please review your order.', {
        quoteId, quotedTotalMinor: stored.totalMinor, currentTotalMinor: fresh.totalMinor, currency: fresh.currency,
      });
    }

    // ---- 4. durable record BEFORE calling the POS -------------------------
    // If the process dies on the next line, this row is what saves the order.
    const payload = {
      clientRequestId: key,
      storeId: this.storeId,
      kioskId: kioskId ?? null,
      channel: 'kiosk',
      fulfillment: stored.request.fulfillment,
      tableNumber: stored.request.tableNumber,
      promotionCode: stored.request.promotionCode,
      lines: stored.request.lines,
      expectedTotalMinor: fresh.totalMinor,
      currency: fresh.currency,
      notes: typeof notes === 'string' ? notes.slice(0, 500) : '',
      payment: payment ?? null,
    };

    const submission = this.kioskStore.createSubmission({
      clientRequestId: key,
      storeId: this.storeId,
      kioskId,
      quoteId,
      payload,
      paymentAccepted: payment?.status === 'approved',
      paymentReference: payment?.reference ?? null,
    });

    this.kioskStore.markQuote(quoteId, 'consumed');
    return this.#attemptSubmission(submission);
  }

  /**
   * One attempt at handing a stored submission to the POS.
   *
   * The three outcomes are kept strictly apart:
   *   - confirmed: the POS has the order.
   *   - pending:   the POS is unreachable; the row stays queued and is retried.
   *                If payment was accepted this becomes an ops exception
   *                rather than ever being abandoned.
   *   - rejected:  the POS understood and refused. Retrying cannot help.
   */
  async #attemptSubmission(submission) {
    try {
      const order = await this.adapter.submitOrder(submission.payload);
      const updated = this.kioskStore.markSubmissionSubmitted(submission.id, {
        posOrderId: order.posOrderId,
        posOrderNumber: order.posOrderNumber,
      });
      this.kioskStore.logEvent({
        storeId: this.storeId,
        kioskId: submission.kioskId,
        eventType: 'order.confirmed',
        payload: {
          posOrderNumber: order.posOrderNumber,
          totalMinor: order.totalMinor,
          attempts: updated.attempts,
          posReportedDuplicate: order.duplicate === true,
        },
      });
      return {
        status: 'confirmed',
        posOrderId: order.posOrderId,
        posOrderNumber: order.posOrderNumber,
        order,
      };
    } catch (error) {
      if (error instanceof PosRejectedError) {
        // A refusal is final. Mark it so, unless money has already moved — then
        // it needs a human, not a retry loop.
        this.kioskStore.markSubmissionFailed(submission.id, { error: error.message, retryable: false });
        this.kioskStore.logEvent({
          storeId: this.storeId, kioskId: submission.kioskId, level: 'error',
          eventType: 'order.rejected',
          payload: { code: error.code, paymentAccepted: submission.paymentAccepted },
        });
        if (submission.paymentAccepted) {
          this.kioskStore.recordIntegrationIssue(
            this.storeId, 'paid_order_rejected',
            `Payment ${submission.paymentReference ?? '(no reference)'} was accepted but the till refused the order: ${error.message}`,
          );
        }
        throw new AppError(error.code ?? 'pos_rejected', error.message, { status: 409, details: error.details });
      }

      // Unreachable POS: keep the order, retry with backoff.
      const updated = this.kioskStore.markSubmissionFailed(submission.id, {
        error: error.message,
        retryable: true,
      });
      this.kioskStore.logEvent({
        storeId: this.storeId, kioskId: submission.kioskId, level: 'warn',
        eventType: 'order.pending_retry',
        payload: {
          attempts: updated.attempts,
          nextAttemptAt: updated.nextAttemptAt,
          paymentAccepted: submission.paymentAccepted,
          code: error.code ?? 'pos_unavailable',
        },
      });
      if (submission.paymentAccepted) {
        this.kioskStore.recordIntegrationIssue(
          this.storeId, 'paid_order_unconfirmed',
          `Payment ${submission.paymentReference ?? '(no reference)'} was accepted but the till has not confirmed the order yet. Submission ${submission.id}.`,
        );
      }
      return {
        status: 'pending',
        submissionId: submission.id,
        clientRequestId: submission.clientRequestId,
        attempts: updated.attempts,
        nextAttemptAt: updated.nextAttemptAt,
        paymentAccepted: submission.paymentAccepted,
        message: submission.paymentAccepted
          ? 'Your payment went through. We are still confirming your order with the till — please speak to a member of staff with this reference.'
          : 'The till is not responding. Your order is saved and will be sent automatically.',
      };
    }
  }

  // ------------------------------------------------------------- retry queue

  /** Retry every pending submission whose backoff has elapsed. */
  async drainQueue({ limit = 20 } = {}) {
    const due = this.kioskStore.listDueSubmissions({ limit });
    const results = { attempted: 0, confirmed: 0, stillPending: 0, rejected: 0 };
    for (const submission of due) {
      results.attempted += 1;
      try {
        const outcome = await this.#attemptSubmission(submission);
        if (outcome.status === 'confirmed') results.confirmed += 1;
        else results.stillPending += 1;
      } catch {
        results.rejected += 1;
      }
    }
    if (results.attempted > 0) this.logger?.info?.('checkout.queue_drained', results);
    return results;
  }

  startQueueWorker({ intervalSeconds = 10 } = {}) {
    if (this.queueTimer) return;
    this.queueTimer = setInterval(() => {
      this.drainQueue().catch((error) => this.logger?.error?.('checkout.queue_error', { message: error.message }));
    }, intervalSeconds * 1000);
    this.queueTimer.unref?.();
    this.logger?.info?.('checkout.queue_worker_started', { intervalSeconds });
  }

  stopQueueWorker() {
    if (this.queueTimer) clearInterval(this.queueTimer);
    this.queueTimer = null;
  }

  /** Status of a submission by its idempotency key. */
  async getSubmissionStatus(clientRequestId) {
    const submission = this.kioskStore.findSubmission(String(clientRequestId ?? '').trim());
    if (!submission) return null;
    const order = submission.posOrderId
      ? await this.adapter.getOrderStatus(submission.posOrderId).catch(() => null)
      : null;
    return {
      clientRequestId: submission.clientRequestId,
      status: submission.status === 'submitted' ? 'confirmed' : submission.status,
      posOrderId: submission.posOrderId,
      posOrderNumber: submission.posOrderNumber,
      attempts: submission.attempts,
      lastError: submission.lastError,
      nextAttemptAt: submission.nextAttemptAt,
      paymentAccepted: submission.paymentAccepted,
      order,
    };
  }
}

function normaliseTableNumber(value, store) {
  if (!store?.tableNumberEnabled) return null;
  const text = String(value ?? '').trim();
  if (!text) return null;
  if (!/^[\w -]{1,12}$/.test(text)) return null;
  return text;
}

/** Map adapter errors onto the API error model. */
function translatePosError(error) {
  if (error instanceof PosRejectedError) {
    return new AppError(error.code ?? 'pos_rejected', error.message, { status: 409, details: error.details });
  }
  if (error instanceof PosIntegrationError) {
    return posUnavailable('The till system is not responding. Please try again or ask a member of staff.', {
      code: error.code,
    });
  }
  return error;
}
